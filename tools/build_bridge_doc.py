"""Writes one section per bridge into docs/routing-rules.md, between the BRIDGES markers, from data/bridges.json.

Edit data/bridge_names.json (names, streets, notes), regenerate data/bridges.json, then run this.
Usage: python tools/build_bridge_doc.py
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
DOC = os.path.join(HERE, "..", "docs", "routing-rules.md")
B = json.load(open(os.path.join(HERE, "..", "data", "bridges.json")))["bridges"]
START, END = "<!-- BRIDGES:START (generated by tools/build_bridge_doc.py, do not edit by hand) -->", "<!-- BRIDGES:END -->"


def fmt_pt(p):
    return f"{p[0]:.6f}, {p[1]:.6f}"


def lane_text(c):
    l = c.get("lane", {})
    if l.get("type") == "one-way":
        return f"{l['side']} side, one-way"
    if l.get("type") == "two-way":
        return f"two-way path ({l['side']} side in map data)"
    if l.get("type", "").startswith("roadway"):
        return f"bike lane on the roadway, keep right ({l['side']} side)"
    return "not tagged in map data"


out = []
for b in B:
    pos = b["position"]
    out.append(f"### {b['name']}")
    out.append("")
    out.append("| | |")
    out.append("|---|---|")
    out.append(f"| ID | `{b['id']}` |")
    out.append(f"| Category | {b['category_label']} (`{b['category']}`) |")
    out.append(f"| Uses | {', '.join(b['modes'])} |")
    out.append(f"| Bike facility | {b['bike_facility']} |")
    if b.get("transit"):
        out.append(f"| Transit | {b['transit']} |")
    out.append(f"| Structure | {b['type']}, {b['year']} |")
    out.append(f"| Aliases | {', '.join(b['aliases'])} |")
    out.append(f"| Misspellings | {', '.join(b['misspellings'])} |")
    if b["colors"]:
        note = "" if b.get("colors_verified") else " (unverified, from photo captions)"
        out.append(f"| Colors | {', '.join(b['colors'])}{note} |")
    out.append(f"| Carries | {b['carries']} |")
    out.append(f"| Streets | {', '.join(b['streets'])} |")
    for side, text in b["ends_described"].items():
        out.append(f"| {side.capitalize()} end | {text} |")
    rel = [pos["sequence"]]
    for key, label in (("north_neighbor", "North"), ("south_neighbor", "South"), ("west_neighbor", "West"), ("east_neighbor", "East")):
        if key in pos:
            n = pos[key]
            dist = f"{n['river_miles']} river miles" if "river_miles" in n else f"{n['km']} km"
            rel.append(f"{label}: {n['name']} ({dist})")
    rel.append("Nearest: " + ", ".join(f"{n['name']} {n['km']} km {n['direction']}" for n in pos["nearest"]))
    out.append(f"| Position | {'. '.join(rel)} |")
    access = {"yes": "Yes", "no": "No, closed to bikes", "limited": "Limited, not offered"}[b["bike_access"]]
    out.append(f"| Bikes | {access}. {b['bike_note'] or ''} |")
    if b.get("preference") and b["preference"] != "normal":
        out.append(f"| Preference | {b['preference']} |")
    for side, p in b["approaches"].items():
        out.append(f"| GPS, {side} approach | {fmt_pt(p)} |")
    for d, c in b["crossings"].items():
        if not c["offered"]:
            continue
        v = "validated" if c.get("validated") else ("FAILED validation" if c.get("validated") is False else "not validated")
        out.append(f"| {d.capitalize()} | {fmt_pt(c['from'])} to {fmt_pt(c['to'])}. Lane: {lane_text(c)}. {v} |")
    for side, rows in b["nearby_bike_routes"].items():
        if rows:
            names = []
            for r in rows:
                if r["name"] not in names:
                    names.append(r["name"])
            out.append(f"| Bike routes near {side} end | {', '.join(names[:5])} |")
    out.append("")

block = START + "\n\n" + "\n".join(out) + "\n" + END
doc = open(DOC).read()
if START in doc:
    doc = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda m: block, doc, flags=re.S)
else:
    doc = doc.rstrip() + "\n\n## 9. Bridges\n\nOne section per crossing, generated from `data/bridges.json`. To change a fact, edit `data/bridge_names.json` and rebuild (see `data/README.md`). Nearby bike routes come from OpenStreetMap tags, not the city's official list.\n\n" + block + "\n"
open(DOC, "w").write(doc)
print("wrote", len(B), "bridge sections")
